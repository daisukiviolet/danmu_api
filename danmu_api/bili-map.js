// danmu_api/bili-map.js
// 片名 → B 站 season_id 的映射表
//
// 为什么需要它
// B 站对机房 IP 做了搜索层封禁：从 Vercel 出口请求影视/番剧搜索，
// 服务端直接返回 numResults:0（连搜索页 SSR 数据里都是 media_ft:{numResults:0}）。
// 带登录 Cookie 也一样，封的是 IP 段。
// 但 season_id 一旦知道，pgc/view/web/season 和弹幕接口都是通的。
//
// 所以：查到 ss 号之后写进这张表，播放器里按片名搜也能直接命中，
// 不用每次手动粘 ss 号。
//
// 怎么填
//   1) 本机跑： python bili-find.py 片名
//   2) 输出里拿到 ss 号（例如 ss218526）
//   3) 在下面加一行："片名": "ss218526"
//   4) git commit && git push，Vercel 会自动重新部署
//
// 匹配规则（bili.js 里的 lookupMap）
//   · 完全一致优先
//   · 其次「关键词包含表里的片名」，取最长匹配
//     所以登记了「蜘蛛侠：崭新之日」，搜索「蜘蛛侠：崭新之日.2026.2160p」也能命中
//   · 值可以是 ss 号、ep 号，也可以是完整 B 站链接

